#!/usr/bin/env python3
"""Download the public PokeDB export tables used by the IZI Dex importer.

Raw export files are downloaded to a temporary/local folder and are not meant
to be committed. The transformed, compact encounter catalog is generated by
import_izi_dex_pokedb.py.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

BASE_URL = "https://cdn.pokedb.org/data_export_"
TABLE_MINIMUMS = {
    "encounters": 10_000,
    "pokemon_forms": 1_000,
    "location_areas": 1_000,
    "locations": 500,
    "encounter_methods": 50,
}
USER_AGENT = "IZI-Dex-Data-Importer/1.0 (+https://github.com/izidororichart/pokeapi)"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Download and validate the PokeDB JSON export tables for IZI Dex."
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "data" / "pokedb",
        help="Folder for temporary PokeDB JSON inputs (default: data/pokedb).",
    )
    parser.add_argument("--timeout", type=int, default=120, help="HTTP timeout in seconds.")
    parser.add_argument("--retries", type=int, default=3, help="Number of download attempts.")
    return parser.parse_args()


def validate_export(path: Path, table: str) -> int:
    try:
        with path.open("r", encoding="utf-8") as handle:
            payload: Any = json.load(handle)
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValueError(f"{table}: downloaded file is not valid JSON: {exc}") from exc

    if not isinstance(payload, list):
        raise ValueError(f"{table}: expected a JSON array, received {type(payload).__name__}.")
    if not all(isinstance(row, dict) for row in payload):
        raise ValueError(f"{table}: one or more rows are not JSON objects.")

    minimum = TABLE_MINIMUMS[table]
    if len(payload) < minimum:
        raise ValueError(
            f"{table}: export contains only {len(payload):,} rows; "
            f"expected at least {minimum:,}. Refusing to import an incomplete export."
        )
    return len(payload)


def download_table(output_dir: Path, table: str, timeout: int, retries: int) -> tuple[int, int]:
    url = f"{BASE_URL}{table}_json"
    destination = output_dir / f"{table}.json"
    temporary = output_dir / f".{table}.json.download"

    request = urllib.request.Request(
        url,
        headers={
            "User-Agent": USER_AGENT,
            "Accept": "application/json",
        },
    )
    last_error: Exception | None = None

    for attempt in range(1, retries + 1):
        try:
            with urllib.request.urlopen(request, timeout=timeout) as response:
                if response.status != 200:
                    raise OSError(f"HTTP {response.status}")
                with temporary.open("wb") as output:
                    while True:
                        chunk = response.read(1024 * 1024)
                        if not chunk:
                            break
                        output.write(chunk)

            rows = validate_export(temporary, table)
            size = temporary.stat().st_size
            temporary.replace(destination)
            return rows, size
        except (OSError, urllib.error.URLError, ValueError) as exc:
            last_error = exc
            temporary.unlink(missing_ok=True)
            if attempt < retries:
                time.sleep(min(2 ** attempt, 10))

    raise RuntimeError(f"Could not download PokeDB table '{table}' after {retries} attempts: {last_error}")


def main() -> int:
    options = parse_args()
    if options.timeout < 1 or options.retries < 1:
        print("--timeout and --retries must be positive integers.", file=sys.stderr)
        return 2

    output_dir = options.output_dir.expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    total_rows = 0
    total_bytes = 0
    try:
        for table in TABLE_MINIMUMS:
            rows, size = download_table(output_dir, table, options.timeout, options.retries)
            total_rows += rows
            total_bytes += size
            print(f"{table}: {rows:,} rows ({size / 1024 / 1024:.1f} MiB)")
    except (OSError, RuntimeError, ValueError) as exc:
        print(f"PokeDB download failed: {exc}", file=sys.stderr)
        return 1

    print(
        f"Validated {len(TABLE_MINIMUMS)} PokeDB tables: "
        f"{total_rows:,} rows, {total_bytes / 1024 / 1024:.1f} MiB."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
